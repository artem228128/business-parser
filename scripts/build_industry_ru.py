def norm(s: str) -> str:
    return re.sub(r"\s+", " ", s.strip().lower())


def translate_token(token: str) -> str:
    t = token.lower().replace("-", "_")
    if t in WORD:
        return WORD[t]
    t2 = t.replace("_", " ")
    if t2 in PHRASE:
        return PHRASE[t2]
    if t2 in WORD:
        return WORD[t2]
    # try split compound with underscore
    if "_" in t:
        parts = t.split("_")
        if all(p in WORD for p in parts):
            return " ".join(WORD[p] for p in parts)
        parts_tr = [translate_token(p) for p in parts]
        if any(parts_tr[i] != parts[i] for i in range(len(parts))):
            return " ".join(parts_tr)
    return token.replace("_", " ")


def translate_segment(seg: str) -> str:
    seg = seg.strip()
    if not seg:
        return seg
    if re.search(r"[;,]", seg):
        parts = re.split(r"[;,]", seg)
        return "; ".join(translate_segment(p.strip()) for p in parts if p.strip())
    low = norm(seg.replace("_", " "))
    if low in PHRASE:
        return PHRASE[low]
    if low in WORD:
        return WORD[low]
    # label style with spaces
    if " " in low and low in PHRASE:
        return PHRASE[low]
    words = re.split(r"[\s_]+", seg)
    out = [translate_token(w) for w in words if w]
    return " ".join(out)


def translate_label(industry: str, label: str) -> str:
    if industry in ID_OVERRIDE:
        return ID_OVERRIDE[industry]
    tag = industry.split(":", 1)[-1] if ":" in industry else label
    if tag and tag not in ("yes", "no"):
        from_tag = translate_segment(tag)
        if from_tag and not re.search(r"[A-Za-z]{4,}", from_tag):
            return from_tag
    tag_low = norm(tag.replace("_", " "))
    if tag_low in PHRASE:
        return PHRASE[tag_low]
    lab_low = norm(label.replace("_", " "))
    if lab_low in PHRASE:
        return PHRASE[lab_low]
    if tag_low in WORD:
        return WORD[tag_low]
    parts = re.split(r"[;,]", label)
    if len(parts) > 1:
        return "; ".join(translate_segment(p) for p in parts)
    return translate_segment(label or tag)


def main() -> None:
    con = sqlite3.connect(f"file:{DB}?mode=ro", uri=True)
    rows = con.execute(
        "SELECT DISTINCT industry, industry_label FROM companies WHERE industry != ''"
    ).fetchall()
    out: dict[str, str] = {}
    for ind, label in rows:
        out[ind] = translate_label(ind, label or "")
    OUT.write_text(json.dumps(out, ensure_ascii=False, indent=0), encoding="utf-8")
    print(f"wrote {len(out)} entries -> {OUT}")


if __name__ == "__main__":
    main()
